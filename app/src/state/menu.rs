//! Context menu entries of list rows

use super::list::Tab;

/// One context menu entry; the UI maps it to a label and an action.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MenuItem {
    AddToSnippets,
    DeleteFromHistory,
    Edit,
    Delete,
    AddNew,
    MoveUp,
    MoveDown,
    NewFolder,
    NewSeparator,
    NewCommand,
    NewFile,
    NewDirectory,
    NewUrl,
    /// Opens the special item palette (ADR-040).
    NewSpecial,
    AddToLauncher,
    OpenFolder,
    CopyPath,
    RemoveFromHistory,
    /// `launcher.json` fails to parse: open the Launcher settings.
    FixConfig,
}

impl MenuItem {
    pub const ALL: [MenuItem; 19] = {
        use MenuItem::*;
        [
            AddToSnippets,
            DeleteFromHistory,
            Edit,
            Delete,
            AddNew,
            MoveUp,
            MoveDown,
            NewFolder,
            NewSeparator,
            NewCommand,
            NewFile,
            NewDirectory,
            NewUrl,
            NewSpecial,
            AddToLauncher,
            OpenFolder,
            CopyPath,
            RemoveFromHistory,
            FixConfig,
        ]
    };
}

/// An entry, or the "New" submenu of launcher rows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MenuEntry {
    Item(MenuItem),
    New(Vec<MenuItem>),
}

/// Menu sections, separated in the menu.
pub type Sections = Vec<Vec<MenuEntry>>;

fn items(sections: Vec<Vec<MenuItem>>) -> Sections {
    sections
        .into_iter()
        .map(|s| s.into_iter().map(MenuEntry::Item).collect())
        .collect()
}

/// Up and down moves for row `index` of `len` (empty at both ends).
fn moves(index: usize, len: usize) -> Vec<MenuItem> {
    let mut moves = Vec::new();
    if index > 0 {
        moves.push(MenuItem::MoveUp);
    }
    if index + 1 < len {
        moves.push(MenuItem::MoveDown);
    }
    moves
}

/// Sections for row `index` of `len` visible rows of the Clipboard or
/// Snippets tab. Empty when the tab has no menu.
pub fn row_menu(tab: Tab, index: usize, len: usize) -> Sections {
    use MenuItem::*;
    let has_row = index < len;
    items(match tab {
        Tab::Clipboard if has_row => vec![vec![AddToSnippets], vec![DeleteFromHistory]],
        Tab::Snippets if has_row => {
            let moves = moves(index, len);
            let mut sections = vec![vec![Edit, AddNew]];
            if !moves.is_empty() {
                sections.push(moves);
            }
            sections.push(vec![Delete]);
            sections
        },
        Tab::Snippets => vec![vec![AddNew]],
        Tab::Clipboard | Tab::Launcher => Vec::new(),
    })
}

/// What a Launcher row is, for its menu.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LauncherRow {
    /// A node of the tree, row `index` of `len` in its level; `searching`
    /// when it is a search result (no moves or new items there).
    Node {
        separator: bool,
        index: usize,
        len: usize,
        searching: bool,
    },
    /// A row generated by an `apps` or `power` node, or an installed app
    /// found by search.
    Generated,
    /// A recent file; `removable` when it comes from the system history.
    Recent { removable: bool },
    /// A file or folder listed by a `directory` level.
    Listed,
    /// A row of a generated level without actions ("open this folder").
    Fixed,
    /// A folder without rows.
    Empty,
}

/// The "New" submenu of launcher rows.
const NEW: [MenuItem; 7] = {
    use MenuItem::*;
    [NewFolder, NewSeparator, NewCommand, NewFile, NewDirectory, NewUrl, NewSpecial]
};

/// Sections for a Launcher row; `editable` is false while `launcher.json`
/// fails to parse.
pub fn launcher_menu(row: LauncherRow, editable: bool) -> Sections {
    use MenuItem::*;
    let new = || MenuEntry::New(NEW.to_vec());
    match row {
        LauncherRow::Recent { removable } => {
            let mut sections = vec![vec![OpenFolder, CopyPath]];
            if removable {
                sections.push(vec![RemoveFromHistory]);
            }
            return items(sections);
        },
        LauncherRow::Fixed => return Vec::new(),
        LauncherRow::Listed if !editable => return items(vec![vec![OpenFolder, CopyPath]]),
        _ => {},
    }
    if !editable {
        return items(vec![vec![FixConfig]]);
    }
    match row {
        LauncherRow::Node {
            separator,
            index,
            len,
            searching,
        } => {
            let edit = (!separator).then_some(MenuEntry::Item(Edit));
            if searching {
                let mut sections: Sections = edit.into_iter().map(|e| vec![e]).collect();
                sections.push(vec![MenuEntry::Item(Delete)]);
                return sections;
            }
            let mut sections = vec![edit.into_iter().chain([new()]).collect()];
            let moves = moves(index, len);
            if !moves.is_empty() {
                sections.push(moves.into_iter().map(MenuEntry::Item).collect());
            }
            sections.push(vec![MenuEntry::Item(Delete)]);
            sections
        },
        LauncherRow::Generated => items(vec![vec![AddToLauncher]]),
        LauncherRow::Listed => items(vec![vec![OpenFolder, CopyPath], vec![AddToLauncher]]),
        LauncherRow::Empty => vec![vec![new()]],
        LauncherRow::Recent { .. } | LauncherRow::Fixed => unreachable!("handled above"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use MenuItem::*;

    fn flat(sections: &Sections) -> Vec<Vec<MenuItem>> {
        sections
            .iter()
            .map(|s| {
                s.iter()
                    .map(|e| match e {
                        MenuEntry::Item(i) => *i,
                        MenuEntry::New(_) => AddNew,
                    })
                    .collect()
            })
            .collect()
    }

    fn node(index: usize, len: usize) -> LauncherRow {
        LauncherRow::Node {
            separator: false,
            index,
            len,
            searching: false,
        }
    }

    #[test]
    fn clipboard_rows() {
        assert_eq!(
            flat(&row_menu(Tab::Clipboard, 0, 2)),
            [vec![AddToSnippets], vec![DeleteFromHistory]]
        );
        assert!(row_menu(Tab::Clipboard, 0, 0).is_empty());
    }

    #[test]
    fn snippet_moves_depend_on_position() {
        let menu = |i, len| flat(&row_menu(Tab::Snippets, i, len));
        assert_eq!(menu(0, 3), [vec![Edit, AddNew], vec![MoveDown], vec![Delete]]);
        assert_eq!(menu(1, 3), [vec![Edit, AddNew], vec![MoveUp, MoveDown], vec![Delete]]);
        assert_eq!(menu(2, 3), [vec![Edit, AddNew], vec![MoveUp], vec![Delete]]);
        assert_eq!(menu(0, 1), [vec![Edit, AddNew], vec![Delete]]);
    }

    #[test]
    fn empty_snippets_only_add_and_launcher_has_no_row_menu() {
        assert_eq!(flat(&row_menu(Tab::Snippets, 0, 0)), [vec![AddNew]]);
        assert!(row_menu(Tab::Launcher, 0, 3).is_empty());
    }

    #[test]
    fn launcher_nodes_follow_the_snippet_sections() {
        let new = MenuEntry::New(NEW.to_vec());
        assert_eq!(
            NEW,
            [NewFolder, NewSeparator, NewCommand, NewFile, NewDirectory, NewUrl, NewSpecial]
        );
        assert_eq!(
            launcher_menu(node(1, 3), true),
            [
                vec![MenuEntry::Item(Edit), new.clone()],
                vec![MenuEntry::Item(MoveUp), MenuEntry::Item(MoveDown)],
                vec![MenuEntry::Item(Delete)]
            ]
        );
        let separator = LauncherRow::Node {
            separator: true,
            index: 0,
            len: 1,
            searching: false,
        };
        assert_eq!(
            launcher_menu(separator, true),
            [vec![new.clone()], vec![MenuEntry::Item(Delete)]]
        );
        assert_eq!(launcher_menu(LauncherRow::Empty, true), [vec![new]]);
    }

    #[test]
    fn search_results_only_edit_or_delete() {
        let found = LauncherRow::Node {
            separator: false,
            index: 2,
            len: 5,
            searching: true,
        };
        assert_eq!(flat(&launcher_menu(found, true)), [vec![Edit], vec![Delete]]);
    }

    #[test]
    fn generated_and_recent_rows() {
        assert_eq!(flat(&launcher_menu(LauncherRow::Generated, true)), [vec![AddToLauncher]]);
        assert_eq!(
            flat(&launcher_menu(LauncherRow::Recent { removable: true }, true)),
            [vec![OpenFolder, CopyPath], vec![RemoveFromHistory]]
        );
        assert_eq!(
            flat(&launcher_menu(LauncherRow::Recent { removable: false }, false)),
            [vec![OpenFolder, CopyPath]]
        );
    }

    #[test]
    fn listed_files_open_copy_or_add_and_fixed_rows_have_no_menu() {
        assert_eq!(
            flat(&launcher_menu(LauncherRow::Listed, true)),
            [vec![OpenFolder, CopyPath], vec![AddToLauncher]]
        );
        assert_eq!(flat(&launcher_menu(LauncherRow::Listed, false)), [vec![OpenFolder, CopyPath]]);
        assert!(launcher_menu(LauncherRow::Fixed, true).is_empty());
    }

    #[test]
    fn an_invalid_file_only_offers_to_fix_it() {
        for row in [node(0, 2), LauncherRow::Generated, LauncherRow::Empty] {
            assert_eq!(flat(&launcher_menu(row, false)), [vec![FixConfig]]);
        }
    }
}
